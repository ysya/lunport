const LIGHT = [0x24292f, 0xb42332, 0x246b35, 0x806000, 0x1458b0, 0x8249a5, 0x146c73, 0x57606a, 0x6e7781, 0xcf2438, 0x2d7c40, 0x936b00, 0x2671ce, 0x9c55be, 0x1c7d86, 0x8c959f];
export function terminalColors(value: unknown, mode: ResolvedTheme): TerminalThemeColors {
  const theme = getColorTheme(value);
  const colors = theme[mode];
  const rgb = (hex: string) => parseInt(hex.slice(1), 16);
  return { foreground: rgb(colors["--foreground"]), background: rgb(colors["--background"]), cursor: rgb(colors["--primary"]), palette: [...(mode === "dark" ? DARK[theme.id] : LIGHT)] };
}
